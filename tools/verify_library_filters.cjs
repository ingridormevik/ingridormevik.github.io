const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const control = () => ({value:'',events:{}, addEventListener(type, fn){this.events[type]=fn;},focus(){this.focused=true;}});
const search=control(), topic=control(), reset=control(), form=control(), count={textContent:''};
search.closest=()=>form;
const books=[{textContent:'Hamlet Narrative',dataset:{topic:'Narrative and games'}},{textContent:'Design Justice',dataset:{topic:'Design and participation'}},{textContent:'Data Feminism',dataset:{topic:'Data and power'}}];
const nodes={'#al-search':search,'#al-topic':topic,'#al-reset':reset,'#al-count':count};
vm.runInNewContext(fs.readFileSync('labs/academic-library.js','utf8'),{document:{querySelector:key=>nodes[key],querySelectorAll:()=>books}});
assert.equal(count.textContent,'3 sources');
search.value='hamlet';search.events.input();
assert.equal(count.textContent,'1 source of 3 · Filters applied');
assert.equal(books.filter(b=>!b.hidden).length,1);
topic.value='Data and power';topic.events.change();
assert.equal(books.filter(b=>!b.hidden).length,0);
assert(count.textContent.startsWith('No matches'));
reset.events.click();
assert(books.every(b=>!b.hidden));assert.equal(count.textContent,'3 sources');assert(search.focused);
topic.value='Design and participation';topic.events.change();
assert(!books[1].hidden && books[0].hidden);
console.log('PASS: library text/topic intersection, singular count, no matches and reset to all sources.');
