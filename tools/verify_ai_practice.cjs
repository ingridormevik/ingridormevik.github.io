const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const html = fs.readFileSync('labs/vibecoding.html', 'utf8');
const code = html.match(/<pre><code>([\s\S]*?)<\/code><\/pre>/)[1];
const story = {textContent: 'My own starting sentence.'};
let click;
const button = {addEventListener: (event, fn) => { assert.equal(event, 'click'); click = fn; }};
const run = () => vm.runInNewContext(code, {document: {querySelector: id => id === '#story' ? story : button}});
run();
assert.equal(story.textContent, 'My own starting sentence.');
click();
assert.equal(story.textContent, 'Someone else remembers this place differently.');
click();
assert.equal(story.textContent, 'My own starting sentence.');
click();
assert.equal(story.textContent, 'Someone else remembers this place differently.');
story.textContent = 'My own starting sentence.';
run();
assert.equal(story.textContent, 'My own starting sentence.');
assert(!html.includes('data-va-'));
console.log('PASS: AI example alternates both sentences, preserves personal starting text and resets on reload; no arena controls.');
